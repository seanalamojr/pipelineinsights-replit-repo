-- Prediction history is append-only by model version.

CREATE TABLE IF NOT EXISTS player_prop_predictions (
    prediction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id TEXT NOT NULL,
    match_id TEXT NOT NULL,
    sport TEXT NOT NULL,
    prop_type TEXT NOT NULL,
    prediction NUMERIC(12, 4) NOT NULL,
    lowerci NUMERIC(12, 4),
    upperci NUMERIC(12, 4),
    modelversion TEXT NOT NULL,
    predictiontimestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT player_prop_predictions_match_fk
        FOREIGN KEY (match_id, player_id)
        REFERENCES matches (match_id, player_id),
    CONSTRAINT player_prop_predictions_model_version_uq
        UNIQUE (player_id, match_id, prop_type, modelversion)
);

CREATE INDEX IF NOT EXISTS player_prop_predictions_event_lookup_idx
    ON player_prop_predictions (sport, prop_type, predictiontimestamp);
CREATE INDEX IF NOT EXISTS player_prop_predictions_model_version_idx
    ON player_prop_predictions (modelversion);

