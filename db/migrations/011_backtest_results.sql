-- Checkpoint 8: append-only walk-forward evaluation results.

CREATE TABLE IF NOT EXISTS model_backtest_results (
    result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modelversion TEXT NOT NULL,
    sport TEXT NOT NULL,
    stat_target TEXT NOT NULL,
    fold_number INTEGER NOT NULL,
    metric TEXT NOT NULL,
    metric_value NUMERIC(16, 8),
    cutoff_date DATE NOT NULL,
    test_end_date DATE NOT NULL,
    row_count INTEGER NOT NULL,
    run_timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS model_backtest_results_lookup_idx
    ON model_backtest_results (
        sport,
        stat_target,
        modelversion,
        cutoff_date,
        fold_number
    );

INSERT INTO pipelineinsights_schema_migrations (version)
VALUES ('011_backtest_results')
